function makeLearningPlayer(
  id: string,
  name: string,
  program: TankBlueprint['program'],
  overrides?: Partial<TankBlueprint['assembly']>
): TankBlueprint {
  return {
    version: 1,
    id,
    name,
    color: '#38bdf8',
    assembly: {
      chassis: overrides?.chassis ?? 'standard',
      mainGun: overrides?.mainGun ?? 'standard',
      radar: overrides?.radar ?? 'balanced',
      cpu: overrides?.cpu ?? 'mini_4x4',
      subWeapon: overrides?.subWeapon ?? 'none',
    },
    program,
  };
}

