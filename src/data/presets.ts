import { CHIP_DEFINITIONS } from './chips';
import {
  ChipProgram,
  ChipType,
  CoordinateMode,
  FirePowerTier,
  GridCell,
  GridCoord,
  GridSize,
  TankBlueprint,
  TutorialStage,
} from '../types/game';

export function createEmptyCells(size: GridSize): (GridCell | null)[][] {
  return Array.from({ length: size }, () => Array.from({ length: size }, () => null));
}

export function makeCell(
  id: string,
  type: ChipType,
  params?: Record<string, string | number>,
  links?: { next?: GridCoord | null; yes?: GridCoord | null; no?: GridCoord | null }
): GridCell {
  const def = CHIP_DEFINITIONS[type];
  return {
    id,
    type,
    params: { ...def.defaultParams, ...(params ?? {}) },
    next: links?.next ?? null,
    yes: links?.yes ?? null,
    no: links?.no ?? null,
  };
}

export function buildProgram(
  gridSize: GridSize,
  coordinateMode: CoordinateMode,
  placements: Array<{
    x: number;
    y: number;
    type: ChipType;
    params?: Record<string, string | number>;
    next?: GridCoord | null;
    yes?: GridCoord | null;
    no?: GridCoord | null;
  }>
): ChipProgram {
  const cells = createEmptyCells(gridSize);
  placements.forEach((p, idx) => {
    if (p.y >= 0 && p.y < gridSize && p.x >= 0 && p.x < gridSize) {
      cells[p.y][p.x] = makeCell(`c_${idx}_${p.x}_${p.y}`, p.type, p.params, {
        next: p.next,
        yes: p.yes,
        no: p.no,
      });
    }
  });
  return { gridSize, coordinateMode, cells };
}

